/** Получить отображаемые очки для ответа */
export function getDisplayPts(roundIdx: number, ansIdx: number, basePts: number): number {
  return roundIdx === 3 ? REVERSE_PTS[ansIdx] : basePts * ROUND_MULT[roundIdx];
}
