// Очки за "Игру наоборот" (раунд 4): чем реже ответ, тем больше очков
export const REVERSE_PTS = [15, 30, 60, 120, 180, 240];

// Названия раундов
export const ROUND_NAMES = ['ПРОСТАЯ ИГРА', 'ДВОЙНАЯ ИГРА', 'ТРОЙНАЯ ИГРА', 'ИГРА НАОБОРОТ'];

// Множители очков для раундов 1-3 (раунд 4 использует REVERSE_PTS)
export const ROUND_MULT = [1, 2, 3, 1];

/** Получить отображаемые очки для ответа */
export function getDisplayPts(roundIdx: number, ansIdx: number, basePts: number): number {
  return roundIdx === 3 ? REVERSE_PTS[ansIdx] : basePts * ROUND_MULT[roundIdx];
}
